let updated = 0
for (const [locale, auth] of Object.entries(authByLocale)) {
  const file = path.join(root, `${locale}.json`)
  if (!fs.existsSync(file)) {
    console.warn("skip missing", locale)
    continue
  }
  const data = JSON.parse(fs.readFileSync(file, "utf8"))
  data.auth = auth
  fs.writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`)
  updated++
}
console.log(`Updated auth for ${updated} locales`)
